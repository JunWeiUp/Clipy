/// File I/O is kept off the main actor so a large stack cannot block the menu.
enum NativeScreenshotThumbnailFileStore {
    static func save(
        pngData: Data,
        in directory: URL,
        basename: String,
        format: NativeScreenshotImageProcessor.FileFormat,
        quality: CGFloat
    ) throws -> URL {
        try FileManager.default.createDirectory(at: directory,
                                                withIntermediateDirectories: true)
        let encoded: Data
        if format == .png {
            encoded = pngData
        } else {
            guard let source = CGImageSourceCreateWithData(pngData as CFData, nil),
                  let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
                throw NativeScreenshotImageProcessor.ImageError.invalidImage
            }
            encoded = try NativeScreenshotImageProcessor.encode(
                image, as: format, quality: quality)
        }
        // The random suffix prevents two rapid saves from selecting the same
        // pathname, including when separate cards are saved concurrently.
        let name = "\(basename)-\(UUID().uuidString.prefix(8))"
        let url = directory.appendingPathComponent(name)
            .appendingPathExtension(format.rawValue)
        try encoded.write(to: url, options: .atomic)
        return url
    }

    static func saveAll(
        pngData: [Data],
        in directory: URL,
        basename: String,
        format: NativeScreenshotImageProcessor.FileFormat,
        quality: CGFloat
    ) throws -> [URL] {
        var saved: [URL] = []
        do {
            for (index, data) in pngData.enumerated() {
                try Task<Never, Never>.checkCancellation()
                let name = "\(basename)-\(String(format: "%02d", index + 1))"
                saved.append(try save(pngData: data, in: directory, basename: name,
                                      format: format, quality: quality))
            }
        } catch {
            // A failed batch must not leave a silent partial save. Every path
            // here was generated by this invocation, so rollback is scoped.
            for url in saved { try? FileManager.default.removeItem(at: url) }
            throw error
        }
        return saved
    }
}

/// The hover controls keep the two frequent actions in the center and reserve
/// the corners for dismissal, pinning, editing, and sharing.
struct NativeScreenshotThumbnailHoverLayout {
    let close: CGRect
    let pin: CGRect
    let edit: CGRect
    let share: CGRect
    let copy: CGRect
    let save: CGRect

    static func make(in size: CGSize) -> Self {
        let scale = min(2, max(0.55, min(size.width / 240, size.height / 160)))
        let padding = max(5, (10 * scale).rounded())
        let corner = max(18, (28 * scale).rounded())
        let centerHeight = max(18, (32 * scale).rounded())
        let gap = max(4, (8 * scale).rounded())
        let centerWidth = min(size.width - padding * 2,
                              max(64, (110 * scale).rounded()))
        let centerX = (size.width - centerWidth) / 2
        let saveY = (size.height - centerHeight * 2 - gap) / 2
        return Self(
            close: CGRect(x: padding, y: size.height - padding - corner,
                          width: corner, height: corner),
            pin: CGRect(x: size.width - padding - corner,
                        y: size.height - padding - corner,
                        width: corner, height: corner),
            edit: CGRect(x: padding, y: padding, width: corner, height: corner),
            share: CGRect(x: size.width - padding - corner, y: padding,
                          width: corner, height: corner),
            copy: CGRect(x: centerX, y: saveY + centerHeight + gap,
                         width: centerWidth, height: centerHeight),
            save: CGRect(x: centerX, y: saveY,
                         width: centerWidth, height: centerHeight)
        )
    }
}

