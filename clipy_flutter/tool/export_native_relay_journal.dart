// Generate public migration fixtures using the currently shipping Dart journal.
// No network or application credential store is accessed.
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'package:common_relay/common_relay.dart';

void main() {
  const clock = 1000;
  const scope = 'clipy/test-fixture/android';
  final directory = Directory.systemTemp.createTempSync(
    'clipy-journal-fixture-',
  );
  try {
    final journal = RelayJournal(directory, clock: () => clock);
    final data = Uint8List.fromList([0, 1, 2, 3, 255]);
    journal.prepare(
      scope,
      'pending',
      'peer',
      data,
      60,
      (_) => 'opaque-test-ciphertext',
    );
    journal.prepare(
      scope,
      'complete',
      'peer',
      data,
      60,
      (_) => 'opaque-test-ciphertext',
    );
    journal.complete(scope, 'complete');
    journal.acknowledge(scope, 'peer', 'incoming');
    final files = directory.listSync().whereType<File>().toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    final fixture = {
      'origin':
          'Generated by the shipping common-relay Dart RelayJournal; public test data only',
      'clock': clock,
      'scope': scope,
      'data': data.toList(),
      'files': [
        for (final file in files)
          {
            'name': file.uri.pathSegments.last,
            'record': jsonDecode(file.readAsStringSync()),
          },
      ],
    };
    File(
      '../clipy_android_native/app/src/androidTest/assets/relay/dart-journal-fixture.json',
    ).writeAsStringSync(
      '${const JsonEncoder.withIndent('  ').convert(fixture)}\n',
    );
    stdout.writeln('Exported ${files.length} Dart journal migration fixtures.');
  } finally {
    directory.deleteSync(recursive: true);
  }
}
